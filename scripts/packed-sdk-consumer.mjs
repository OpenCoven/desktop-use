import assert from 'node:assert/strict';
import { createDesktopClient, resolveActionPermissions, desktopExecutionContractV1 } from '@opencoven/openclaw-desktop-use/sdk';
import { CANONICAL_ACTIONS, observationSchemaV1, capabilitiesSchemaV1, canonicalActionsSchemaV1, desktopRequestSchemaV1, desktopResultSchemaV1 } from '@opencoven/openclaw-desktop-use/contracts';
import { Ajv2020 } from 'ajv/dist/2020.js';
import { access, readFile, writeFile } from 'node:fs/promises';
assert.equal(CANONICAL_ACTIONS.length, 18);
for (const schema of [observationSchemaV1, capabilitiesSchemaV1, canonicalActionsSchemaV1]) assert.ok(schema.$schema);
assert.equal(desktopExecutionContractV1.version, 1);
assert.equal(desktopExecutionContractV1.requestSchema, desktopRequestSchemaV1);
const validateRequest = new Ajv2020({ strict: false }).compile(desktopRequestSchemaV1);
const validateResult = new Ajv2020({ strict: false }).compile(desktopResultSchemaV1);
assert.equal(validateRequest({ action: 'stop' }), true);
assert.equal(validateRequest({ action: 'stop', schemaVersion: 2 }), false);
assert.equal(validateRequest({ action: 'click', confirm: true }), false);
assert.equal(validateResult({ content: [{ type: 'text', text: '{}' }], details: { status: 'invented-outcome' } }), false);
const audits = [];
const options = { workspaceDir: process.cwd(), scope: { principalId: 'packed-consumer' }, adapterPath: '/missing/fixture-adapter', auditSink: async event => { audits.push(event); } };
const client = createDesktopClient(options);
let approvals = 0;
const permissions = resolveActionPermissions({ allowedActions: ['health'] });
const snapshot = JSON.stringify(permissions);
const adapter = `${process.cwd()}/health-adapter.cjs`;
const marker = `${process.cwd()}/health-process-started`;
await writeFile(adapter, `#!${process.execPath}\nrequire('node:fs').writeFileSync(${JSON.stringify(marker)},'started');console.log('{"ok":true}')`, { mode: 0o700 });
const healthOnly = createDesktopClient({ ...options, adapterPath: adapter, actionPermissions: permissions, approvalProvider: () => { approvals++; return 'allowed'; } });
const health = await healthOnly.execute({ action: 'health', reason: 'private-health' }, { callId: 'health-only' });
assert.equal(validateResult(health), true, JSON.stringify(validateResult.errors));
assert.equal(health.details.status, 'blocked');
assert.deepEqual(health.details.adapterProbe, { action: 'doctor', status: 'skipped', code: 'ACTION_PROFILE_DENIED' });
const report = health.details.capabilitiesV1;
assert.equal(report.schemaVersion, 1); assert.equal(report.producer.surface, 'sdk');
assert.deepEqual(report.actionPermissions, permissions);
for (const action of ['doctor', 'inspect', 'screenshot', 'click', 'type-text', 'keypress', 'scroll', 'focus']) {
  assert.equal(report.actions[action].state, 'unverified'); assert.equal(report.actions[action].policy.profile, 'denied');
  assert.ok(report.actions[action].surfaces.includes('sdk')); assert.ok(!report.actions[action].surfaces.includes('plugin'));
}
assert.deepEqual(health.details.adapterInvocation, { configuredPath: adapter, resolvedPath: adapter, version: null, phase: 'before-start', processStarted: false, code: 'ACTION_PROFILE_DENIED' });
assert.equal(health.details.repairHints, undefined); assert.equal(health.details.permissionFlow, undefined);
assert.deepEqual(JSON.parse(health.content[0].text), JSON.parse(JSON.stringify(health.details)));
assert.doesNotMatch(JSON.stringify(health), /private-health|MALFORMED_OUTPUT|CAPABILITY_SCHEMA_|Screen Recording|Accessibility|Install coven/);
assert.equal((await healthOnly.execute({ action: 'stop' }, { callId: 'health-stop' })).details.status, 'success');
assert.equal((await healthOnly.execute({ action: 'doctor' }, { callId: 'doctor-denied' })).details.code, 'ACTION_PROFILE_DENIED');
assert.equal(approvals, 0); await assert.rejects(access(marker)); assert.equal(JSON.stringify(permissions), snapshot);
const enabled = createDesktopClient({ ...options, adapterPath: adapter });
assert.equal((await enabled.execute({ action: 'health' }, { callId: 'health-enabled' })).details.status, 'success');
assert.equal(await readFile(marker, 'utf8'), 'started');
assert.deepEqual(audits[0].result, { status: 'blocked', success: false, code: 'ACTION_PROFILE_DENIED' });
assert.doesNotMatch(JSON.stringify(audits), /private-health|capabilitiesV1|approvalId/);
const denied = await client.execute({ action: 'file-write', path: 'denied', content: 'private-content' }, { callId: 'denied' });
assert.equal(validateResult(denied), true, JSON.stringify(validateResult.errors));
assert.equal(denied.details.success, false); await assert.rejects(access('denied'));
const full = createDesktopClient({ ...options, actionPermissions: resolveActionPermissions(), approvalProvider: () => 'allowed' });
const written = await full.execute({ action: 'file-write', path: 'approved', content: 'private-content' }, { callId: 'allowed' });
assert.equal(validateResult(written), true, JSON.stringify(validateResult.errors));
assert.equal(written.details.success, true); assert.equal(await readFile('approved', 'utf8'), 'private-content');
assert.doesNotMatch(JSON.stringify(audits), /private-content/);
await assert.rejects(full.execute({ action: 'file-write', path: 'forged', content: 'none', confirm: true }, { callId: 'forged' }));
console.log('Compiled SDK/contracts: public execution v1 schemas, health-only no-start policy, configured adapter identity, enabled doctor, 18 actions, default denial, explicit approval, effect, private audit and request authority checked.');
