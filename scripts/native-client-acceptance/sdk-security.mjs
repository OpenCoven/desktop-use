// Copy into the disposable installed consumer before execution. No repo imports.
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { createDesktopClient, resolveActionPermissions } from '@opencoven/openclaw-desktop-use/sdk';
import { verifyMacIdentity } from './identity-preflight.mjs';

const root = resolve(process.env.NATIVE_ACCEPTANCE_ROOT);
const adapterPath = resolve(process.env.NATIVE_ACCEPTANCE_ADAPTER);
if (process.platform === 'darwin') await verifyMacIdentity(root, adapterPath);
const fixturePath = resolve(process.env.NATIVE_ACCEPTANCE_FIXTURE_STATE);
const workspace = join(root, 'security-workspace');
await mkdir(workspace, { recursive: true, mode: 0o700 });
const audits = [];
const scope = { principalId: 'native-security', sessionId: 'controlled-fixture' };
const options = { workspaceDir: workspace, adapterPath, scope, actionPermissions: resolveActionPermissions({ actionProfile: 'full' }), auditSink: async event => { audits.push(event); } };
const state = async () => {
  const s = JSON.parse(await readFile(fixturePath));
  return { clicks: s.clicks, keys: s.keys, text: s.text, scrollOffset: s.scrollOffset };
};
const initial = await state();
const fixture = JSON.parse(await readFile(fixturePath));
const request = { action: 'keypress', keys: ['a'], ...(process.platform === 'darwin' ? { app: 'org.opencoven.desktopuse.acceptance', windowId: fixture.windowNumber } : {}) };
const results = [];
async function check(label, client, expected) {
  const result = await client.execute(request, { callId: label });
  assert.equal(result.details.status, expected);
  assert.deepEqual(await state(), initial, `${label} must have no fixture effect`);
  results.push({ label, status: result.details.status, noFixtureEffect: true });
}
await check('missing-provider', createDesktopClient(options), 'needsApproval');
await check('denied', createDesktopClient({ ...options, approvalProvider: () => 'denied' }), 'blocked');
let lateDecision;
let expiredSignal;
const expired = createDesktopClient({ ...options, approvalTimeoutMs: 100, approvalProvider: challenge => { expiredSignal = challenge.signal; return new Promise(resolve => { lateDecision = resolve; }); } });
await check('expired', expired, 'timeout');
assert.equal(expiredSignal.aborted, true);
lateDecision('allowed');
await new Promise(resolve => setTimeout(resolve, 150));
assert.deepEqual(await state(), initial, 'late expiry decision must not resume input');
results.push({ label: 'late-expiry-decision', noFixtureEffect: true });
const plain = createDesktopClient(options);
await assert.rejects(plain.execute({ ...request, confirm: true }, { callId: 'forged-confirm' }));
await assert.rejects(plain.execute({ ...request, workspaceDir: root }, { callId: 'forged-workspace' }));
assert.deepEqual(await state(), initial);
results.push({ label: 'forged-confirm-and-workspace', noFixtureEffect: true });
let resolvePending;
let ready;
const observed = new Promise(resolve => { ready = resolve; });
const pendingClient = createDesktopClient({ ...options, approvalProvider: () => { ready(); return new Promise(resolve => { resolvePending = resolve; }); } });
const pending = pendingClient.execute(request, { callId: 'pending-stop' });
await observed;
const other = createDesktopClient({ ...options, scope: { ...scope, principalId: 'other-principal' } });
const wrong = await other.execute({ action: 'stop' }, { callId: 'wrong-scope-stop' });
assert.equal(wrong.details.success, true);
let settled = false; pending.then(() => { settled = true; });
await new Promise(resolve => setTimeout(resolve, 100));
assert.equal(settled, false, 'another principal cannot stop pending approval');
await pendingClient.execute({ action: 'stop' }, { callId: 'same-scope-stop' });
assert.equal((await pending).details.status, 'cancelled');
resolvePending('allowed');
await new Promise(resolve => setTimeout(resolve, 150));
assert.deepEqual(await state(), initial);
results.push({ label: 'wrong-scope-stop-preserved-pending', verified: true }, { label: 'same-scope-stop-and-late-approval', noFixtureEffect: true });
const controller = new AbortController();
let abortReady;
const abortObserved = new Promise(resolve => { abortReady = resolve; });
const abortClient = createDesktopClient({ ...options, approvalProvider: challenge => { abortReady(); return new Promise(resolve => challenge.signal.addEventListener('abort', () => resolve('allowed'), { once: true })); } });
const aborted = abortClient.execute(request, { callId: 'abort-pending', signal: controller.signal });
await abortObserved; controller.abort();
assert.equal((await aborted).details.status, 'cancelled');
await new Promise(resolve => setTimeout(resolve, 150));
assert.deepEqual(await state(), initial);
results.push({ label: 'abort-pending-and-late-approval', noFixtureEffect: true });
const auditText = JSON.stringify(audits);
assert.doesNotMatch(auditText, /"(?:nonce|mac|approvalId|screenshot_raw|data)"|base64/);
const receipt = { success: true, surface: 'installed-sdk', decisionSource: 'scripted-trusted-host', nativeAdapterConfigured: true, cases: results, auditEvents: audits.length, noFixtureEffect: true, publication: false };
await writeFile(join(root, 'sdk-security-receipt.json'), JSON.stringify(receipt, null, 2)+'\n');
console.log(JSON.stringify(receipt));
